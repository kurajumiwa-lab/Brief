# ── 4. coordinated bursts are damped, not banned ──────────────────────────────


def _burst_post():
    base = NOW - 6 * HOUR
    organic = [{"id": f"o{i}", "user_id": "u-vet", "value": "up", "at": base + i * HOUR} for i in range(5)]
    bursty = [
        {"id": f"b{i}", "user_id": "u-new", "value": "down", "at": base + 5 * HOUR + i * 2000}
        for i in range(14)
    ]
    return {
        "id": "packed",
        "circle_id": "c1",
        "created_at": base,
        "reactions": [*organic, *bursty],
    }


def test_a_cluster_inside_one_minute_is_found():
    found = burst_window(_burst_post()["reactions"])
    assert found["suspected"] is True
    assert found["count"] == 14
    assert found["share"] > RANKING["burst_share"]


def test_a_slow_honest_crowd_is_left_alone():
    base = NOW - 6 * HOUR
    spread = [{"id": f"u{i}", "user_id": "u-vet", "value": "down", "at": base + i * 20 * 60_000} for i in range(20)]
    assert burst_window(spread)["suspected"] is False


def test_a_burst_counts_at_half_weight_and_says_so():
    verdict = compute_verdict(_burst_post(), now_ms=NOW)
    assert verdict["coordination"]["suspected"] is True
    assert verdict["coordination"]["factor"] == RANKING["burst_damping"]
    assert verdict["weighted_participation"] < verdict["participation"]
    assert verdict["participation"] == 19


def test_nobody_is_banned_or_deleted():
    post = _burst_post()
    ranked = rank_posts([post], now_ms=NOW)
    assert len(ranked) == 1
    assert len(ranked[0]["post"]["reactions"]) == 19


# ── 5. the published weights are the ones applied ─────────────────────────────


def test_the_weights_sum_to_one():
    assert sum(RANKING["weights"].values()) == pytest.approx(1, abs=1e-9)


def test_the_four_parts_are_returned_and_bounded():
    post = {"id": "p", "circle_id": "c1", "created_at": NOW - 2 * HOUR, "reactions": _spread(10, 2)}
