# ── 7. standing is weighted, not trusted blindly ──────────────────────────────


def test_a_first_time_account_counts_for_slightly_less_but_still_counts():
    newbie = {"id": "newbie", "reactions_given": 0}
    veteran = {"id": "veteran", "reactions_given": 50}
    reaction = [{"id": "x", "user_id": "newbie", "value": "up", "at": NOW - HOUR}]
    post = {"id": "p", "circle_id": "c1", "created_at": NOW - 2 * HOUR, "reactions": reaction}

    a = compute_verdict(post, users_by_id={"newbie": newbie}, now_ms=NOW)
    b = compute_verdict(
        {**post, "reactions": [{**reaction[0], "user_id": "veteran"}]},
        users_by_id={"veteran": veteran},
        now_ms=NOW,
    )
    assert a["weighted_up"] < b["weighted_up"]
    assert a["up"] == 1


def test_an_outsider_counts_but_for_less():
    """Membership of the *post's* circle is a separate knob from the viewer's circles."""
    insider = {"id": "in", "reactions_given": 50}
    reaction = [{"id": "x", "user_id": "in", "value": "up", "at": NOW - HOUR}]
    post = {"id": "p", "circle_id": "c1", "created_at": NOW - 2 * HOUR, "reactions": reaction}

    member = compute_verdict(post, users_by_id={"in": insider}, circle_member_ids={"in"}, now_ms=NOW)
    outsider = compute_verdict(post, users_by_id={"in": insider}, circle_member_ids=set(), now_ms=NOW)

    assert outsider["weighted_up"] < member["weighted_up"]
    # One established reaction is worth exactly 1 inside the circle…
    assert member["weighted_up"] == pytest.approx(1.0, abs=1e-3)
    # …and the published outsider fraction outside it.
    assert outsider["weighted_up"] == pytest.approx(RANKING["outsider_weight"], abs=1e-3)


# ── 8. determinism ────────────────────────────────────────────────────────────


def test_the_same_data_and_clock_produce_the_same_order():
    posts = [
        {"id": "a", "circle_id": "c1", "created_at": NOW - 2 * HOUR, "reactions": _spread(5, 1)},
        {"id": "b", "circle_id": "c1", "created_at": NOW - 2 * HOUR, "reactions": _spread(9, 3)},
        {"id": "c", "circle_id": "c2", "created_at": NOW - 2 * HOUR, "reactions": _spread(1, 0)},
    ]
    first = [entry["post"]["id"] for entry in rank_posts(posts, now_ms=NOW)]
    second = [entry["post"]["id"] for entry in rank_posts(list(reversed(posts)), now_ms=NOW)]
    assert first == second


# ── 9. the invariant that makes the product the product ───────────────────────


def test_visibility_never_learns_about_reactions():
    """The one thing that must stay true when this moves behind SQL."""
    posts = [
        {"id": "live", "author_id": "u1", "status": "published", "reactions": [{"value": "down"}] * 50},
        {"id": "removed", "author_id": "u1", "status": "removed", "reactions": []},
        {"id": "blocked", "author_id": "u2", "status": "published", "reactions": []},
        {"id": "muted", "author_id": "u3", "status": "published", "reactions": []},
    ]
    visible = visible_posts(posts, blocked_author_ids={"u2"}, muted_author_ids={"u3"})
    assert [post["id"] for post in visible] == ["live"]
    # …and the fifty downvotes are the reason it *is* visible, not the reverse.
    assert visible[0]["reactions"][0]["value"] == "down"


def test_ranking_never_returns_fewer_posts_than_it_was_given():
    posts = [
        {"id": "a", "circle_id": "c1", "created_at": NOW, "reactions": _spread(0, 40)},
        {"id": "b", "circle_id": "c1", "created_at": NOW, "reactions": []},
    ]
    assert len(rank_posts(posts, now_ms=NOW)) == 2


# ── helpers ───────────────────────────────────────────────────────────────────


def _spread(up, down, *, created_at=NOW - 2 * HOUR, hours=2):
    span = hours * HOUR
    total = up + down
    return [
        {
            "id": f"r{i}",
            "user_id": "u-vet" if i % 2 == 0 else "u-mid",
            "value": "up" if i < up else "down",
            "at": round(created_at + (span * (i + 0.5)) / total),
        }
        for i in range(total)
    ]


def _contested_post():
    return {
        "id": "p1",
        "circle_id": "c1",
        "created_at": NOW - 2 * HOUR,
        "reactions": _spread(6, 10, hours=6),
    }
