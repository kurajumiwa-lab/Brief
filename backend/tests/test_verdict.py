# ── 3. disagreement lowers reach and never removes a post ─────────────────────


def test_a_split_community_is_marked_contested():
    verdict = compute_verdict(_contested_post(), now_ms=NOW)
    assert verdict["participation"] >= RANKING["contested_min_reactions"]
    assert verdict["dissent_share"] >= RANKING["contested_dissent_share"]
