"""The Balanced Verdict, pinned on the server.

Two kinds of test live here, and they answer different questions:

  · **Parity** — does this port compute exactly what the prototype computed?
    The fixtures were generated by running ``caesar/src/lib/ranking.js`` itself,
    so this is not "a test of my translation by my translation": the expected
    numbers came out of the JavaScript that the product has been showing people.
  · **Promise** — does the ranking still keep the three claims the interface
    makes? Those are written against behaviour, not numbers, so they survive a
    deliberate re-tuning of weights.

Every test is pure. No database, no request, no clock of its own — ``now_ms`` is
always passed in, which is why this module landed before any table existed.
"""

from __future__ import annotations

import json
import pathlib

import pytest

from app.services.verdict import (
    RANKING,
    burst_window,
    compute_verdict,
    rank_posts,
    score_post,
    visible_posts,
    why_this_appears,
    wilson_lower,
)

HOUR = 3_600_000
NOW = 1_793_000_400_000  # matches the fixture generator

FIXTURE = pathlib.Path(__file__).parent / "fixtures" / "verdict_parity.json"


@pytest.fixture(scope="module")
def parity():
    return json.loads(FIXTURE.read_text())


def users_from(parity):
    return {entry["id"]: entry for entry in parity["users"]}


# ── 1. parity with the running prototype ──────────────────────────────────────


def test_every_published_constant_matches_the_javascript(parity):
    """Guard against a fixture quietly regenerated by the Python itself.

    Every constant, not a sample of three: if a weight is re-tuned in one
    language and not the other, this is the test that notices.
    """
    for name, value in parity["ranking"].items():
        assert name in RANKING, f"{name} exists in the JS constants but not in the port"
        if isinstance(value, dict):
            assert RANKING[name] == value, name
        else:
            assert RANKING[name] == pytest.approx(value, abs=1e-12), name
    assert set(RANKING) - set(parity["ranking"]) == {"outside_circle_fit"}
    assert len(parity["cases"]) >= 9


@pytest.mark.parametrize("case", json.loads(FIXTURE.read_text())["cases"], ids=lambda c: c["id"])
def test_verdict_and_score_match_the_javascript(parity, case):
    users = users_from(parity)
    post = {
        "id": case["id"],
        "circle_id": case["circleId"],
        "created_at": case["createdAt"],
        "reactions": case["reactions"],
    }
    # The prototype's rankPosts applies no circle-membership filter, so the
    # fixture carries none — comparing anything else would be comparing two
    # different functions.
    verdict = compute_verdict(post, users_by_id=users, now_ms=parity["now_ms"])
    expected = case["expected"]["verdict"]

    for field in ("up", "down", "participation", "contested", "needs_more_voices"):
        assert verdict[field] == expected[field], field
    for field in (
        "weighted_up",
        "weighted_down",
        "weighted_participation",
        "agreement",
        "confidence",
        "dissent_share",
    ):
        assert verdict[field] == pytest.approx(expected[field], abs=1e-9), field
    assert verdict["coordination"]["suspected"] == expected["coordination"]["suspected"]
    assert verdict["coordination"]["count"] == expected["coordination"]["count"]
    assert verdict["coordination"]["factor"] == expected["coordination"]["factor"]

    rank = score_post(
        post,
        verdict=verdict,
        viewer_circle_ids=set(parity["viewer_circle_ids"]),
        now_ms=parity["now_ms"],
    )
    assert rank["score"] == pytest.approx(case["expected"]["score"], abs=1e-9)
    assert rank["raised_by_floor"] == case["expected"]["raised_by_floor"]
    for part, value in case["expected"]["parts"].items():
        assert rank["parts"][part] == pytest.approx(value, abs=1e-9), part


def test_the_whole_order_matches_the_javascript(parity):
    posts = [
        {
            "id": case["id"],
            "circle_id": case["circleId"],
            "created_at": case["createdAt"],
            "reactions": case["reactions"],
        }
        for case in parity["cases"]
    ]
    ranked = rank_posts(
        posts,
        users_by_id=users_from(parity),
        viewer_circle_ids=set(parity["viewer_circle_ids"]),
        now_ms=parity["now_ms"],
    )
    assert [entry["post"]["id"] for entry in ranked] == parity["order"]


# ── 2. a small sample cannot decide anything ──────────────────────────────────


def test_two_unanimous_reactions_are_worth_about_a_third_not_a_hundred_percent():
    assert wilson_lower(2, 2) == pytest.approx(0.342, abs=1e-3)


def test_a_real_sample_is_worth_more_than_a_small_one():
    assert wilson_lower(34, 37) > 0.75
    assert wilson_lower(2, 2) < wilson_lower(34, 37)


def test_the_card_says_the_sample_is_small():
    post = {"id": "p", "circle_id": "c1", "created_at": NOW, "reactions": _spread(2, 0)}
    verdict = compute_verdict(post, now_ms=NOW)
    entry = {"post": post, "verdict": verdict, "parts": {"confidence": verdict["confidence"]}}
