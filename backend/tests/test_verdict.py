def test_a_dogpiled_post_still_ranks_below_a_well_supported_one():
    good = {"id": "good", "circle_id": "c1", "created_at": NOW - 2 * HOUR, "reactions": _spread(30, 2)}
    bad = {"id": "bad", "circle_id": "c1", "created_at": NOW - 2 * HOUR, "reactions": _spread(5, 20)}
    ranked = rank_posts([bad, good], now_ms=NOW)
