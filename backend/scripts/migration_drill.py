"""Prove the migrations apply to a database that already has data in it.

    python scripts/migration_drill.py                 # throwaway database, no setup
    python scripts/migration_drill.py --from 0020_market_runs
    python scripts/migration_drill.py --dsn postgresql://… --keep

An empty database is the easy case, and it is the one the test suite uses. The
deployed database is not empty: it holds real vendors, real stock, real trades.
A migration that adds a NOT NULL column without a default, or backfills assuming
no rows, applies perfectly on an empty database and fails on a live one — at
boot, on the first cold start after the deploy that was meant to fix something
else. That failure is invisible until it happens, because the schema is only
ever exercised from nothing.

This builds the schema at an older revision, inserts rows into the tables that
exist at that point, applies every remaining migration exactly as boot does, and
then checks three things:

  1. every migration applied without error,
  2. the rows are still there and unchanged,
  3. the columns added by the later migrations are readable through the models —
     which is what a page actually does.

Rows are generated by introspecting the real schema: every NOT NULL column with
no default is filled with a type-correct value, enum columns take a real enum
label, and foreign keys point at the rows seeded just before them. Nothing is
hard-coded against a particular revision, so the drill keeps working as the
schema grows.

Exit code 0 only if all three hold. Run it against a fresh throwaway database
(default) or a copy — never production.
"""

from __future__ import annotations

import argparse
import asyncio
import os
import sys
import tempfile
import uuid

BACKEND = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, BACKEND)

DEFAULT_FROM = "0010_market_patrons"
ENUMS_CACHE: dict[str, list[str]] = {}


# ── schema introspection ───────────────────────────────────────────────────


def columns(conn, table: str) -> list[tuple[str, str, str, str | None]]:
    with conn.cursor() as cur:
        cur.execute(
            """SELECT column_name, udt_name, is_nullable, column_default
               FROM information_schema.columns
               WHERE table_schema = 'public' AND table_name = %s
               ORDER BY ordinal_position""",
            (table,),
        )
        return cur.fetchall()


def enum_labels(conn) -> dict[str, list[str]]:
    """Every enum type and its labels, in declaration order.

    Read from the live catalog rather than written down here: a drill that
    guesses `SELLING` while the type says `selling` fails for a reason that has
    nothing to do with migrations.
    """
    if ENUMS_CACHE:
        return ENUMS_CACHE
    with conn.cursor() as cur:
        cur.execute(
            "SELECT DISTINCT t.typname FROM pg_type t JOIN pg_enum e ON e.enumtypid = t.oid"
        )
        names = [row[0] for row in cur.fetchall()]
        for name in names:
            cur.execute(
                "SELECT e.enumlabel FROM pg_enum e JOIN pg_type t ON t.oid = e.enumtypid "
                "WHERE t.typname = %s ORDER BY e.enumsortorder",
                (name,),
            )
            ENUMS_CACHE[name] = [row[0] for row in cur.fetchall()]
    return ENUMS_CACHE


def literal(udt: str, enums: dict[str, list[str]]) -> str:
    """A valid SQL literal for one column, by its actual type.

    `udt_name` is Postgres's internal spelling (`int4`, `float8`, `bool`,
    `timestamptz`, `_text`), not the SQL-standard one. Using the standard names
    fell through to the string default and produced
    "invalid input syntax for type integer: x" for every integer column.
    """
    if udt == "uuid":
        return f"'{uuid.uuid4()}'"
    if udt in ("int2", "int4", "int8"):
        return "1"
    if udt in ("float4", "float8", "numeric", "money"):
        return "1.0"
    if udt == "bool":
        return "true"
    if udt.startswith("timestamp") or udt in ("date", "time"):
        return "now()"
    if udt in ("jsonb", "json"):
        return "'{}'::jsonb"
    if udt.startswith("_"):  # arrays are spelled _<element>
        return "'{}'"
    if udt in enums:
        return "'" + enums[udt][0].replace("'", "''") + "'"
    return "'x'"


def seed(conn, table: str, overrides: dict[str, str] | None = None) -> str | None:
    """Insert one row, filling every required column. Returns an error, or None."""
    enums = enum_labels(conn)
    overrides = overrides or {}
    uniq = uuid.uuid4().hex[:6]  # unique constraint failures must not read as migration failures
    names: list[str] = []
    values: list[str] = []
    seen: set[str] = set()

    def add(name: str, expr: str) -> None:
        if name in seen:  # a column reached twice is a syntax error at the duplicate
            return
        seen.add(name)
        names.append(name)
        values.append(expr)

    for name, udt, nullable, default in columns(conn, table):
        if name in overrides:
            add(name, overrides[name])
        elif name in ("business_name", "vendor_handle", "email"):
            add(name, f"'{table}-{name}-{uniq}'")
        elif nullable == "NO" and default is None:
            add(name, literal(udt, enums))

    # Identifiers are quoted. `current_role` is a reserved word (CURRENT_ROLE is a
    # niladic function), so an unquoted column list fails with a bare
    # "syntax error at or near current_role" — something SQLAlchemy never hits
    # because it quotes identifiers itself.
    quoted = ", ".join(f'"{name}"' for name in names)
    try:
        with conn.cursor() as cur:
            cur.execute(f'INSERT INTO "{table}" ({quoted}) VALUES ({", ".join(values)})')
        return None
    except Exception as exc:  # noqa: BLE001 — reported, not raised: one skipped table is fine
        return f"{type(exc).__name__}: {str(exc).splitlines()[0]}"


# ── the drill ──────────────────────────────────────────────────────────────


async def migrate_and_read() -> tuple[dict, dict | None]:
    """One event loop for the whole run.

    The async engine binds to whichever loop first used it; a second
    `asyncio.run()` hands it a closed loop and the failure looks like a database
    error rather than a driver one.
    """
    from app import schema

    result = await schema.upgrade_to_head()
    if result.get("error"):
        return result, None

    from sqlalchemy import select

    from app.database import async_session
    from app.models.stock import StockItem
    from app.models.vendor import Vendor

    async with async_session() as session:
        vendor = (await session.execute(select(Vendor).limit(1))).scalar_one()
        item = (await session.execute(select(StockItem).limit(1))).scalar_one_or_none()
        return result, {
            "vendor": vendor.business_name,
            "handle": vendor.vendor_handle,
            "role": str(vendor.current_role),
            # Columns added by later migrations: exactly what a create_all
            # database is missing, and why a deployed shop front answered
            # "the tables do not exist yet".
            "stock": item.name if item else None,
            "quality": str(item.quality_status) if item else None,
        }


def run(dsn: str, from_revision: str) -> int:
    import psycopg2
    from alembic import command

    from app import schema

    def q(sql, params=None):
        conn = psycopg2.connect(dsn)
        conn.autocommit = True
        try:
            with conn.cursor() as cur:
                cur.execute(sql, params or ())
                return cur.fetchall() if cur.description else None
        finally:
            conn.close()

    print(f"[1] building a schema at {from_revision} ...")
    command.upgrade(schema._config(), from_revision)
    print("    at", q("SELECT version_num FROM alembic_version")[0][0])

    print("[2] inserting rows a months-old deployment would have ...")
    conn = psycopg2.connect(dsn)
    conn.autocommit = True
    seeded: list[str] = []
    try:
        err = seed(conn, "vendors")
        print(f"    {'vendors':18} {'row inserted' if err is None else 'skipped: ' + err[:90]}")
        if err is not None:
            print("\n!! could not seed a vendor — the drill would prove nothing. Stopping.")
            return 1
        seeded.append("vendors")
        vendor_id = q("SELECT id FROM vendors LIMIT 1")[0][0]

        # Children point at the parent; without it the insert fails on a foreign
        # key, which says nothing about the migrations.
        children = [
            ("stock_items", {"vendor_id": f"'{vendor_id}'"}),
            ("vendor_profiles", {"vendor_id": f"'{vendor_id}'"}),
        ]
        for table, overrides in children:
            err = seed(conn, table, overrides)
            print(f"    {table:18} {'row inserted' if err is None else 'skipped: ' + err[:90]}")
            if err is None:
                seeded.append(table)

        # stock_movements needs both ends of the movement and the item itself.
        stock_id = q("SELECT id FROM stock_items LIMIT 1")
        movement = {"from_vendor_id": f"'{vendor_id}'", "to_vendor_id": f"'{vendor_id}'"}
        if stock_id:
            movement["stock_item_id"] = f"'{stock_id[0][0]}'"
        err = seed(conn, "stock_movements", movement)
        print(f"    {'stock_movements':18} {'row inserted' if err is None else 'skipped: ' + err[:90]}")
        if err is None:
            seeded.append("stock_movements")
    finally:
        conn.close()

    before = {t: q(f'SELECT count(*) FROM "{t}"')[0][0] for t in seeded}
    snapshot = tuple(q("SELECT business_name, vendor_handle, email FROM vendors LIMIT 1")[0])
    print(f"    rows before migration: {before}")

    print("[3] applying every remaining migration, as boot does ...")
    result, read = asyncio.run(migrate_and_read())
    print(
        f"    ran={result.get('ran')} applied={len(result.get('applied') or [])} "
        f"stamped={len(result.get('stamped_revisions') or [])}"
    )
    print(f"    at head: {result.get('at_head')} ({result.get('current')})")
    if result.get("error"):
        print("\n!! a real deployment would have failed its first boot:")
        print("  ", result["error"])
        return 1

    print("[4] is the data still there, and readable through the models? ...")
    after = {t: q(f'SELECT count(*) FROM "{t}"')[0][0] for t in seeded}
    if after != before:
        print(f"\n!! row counts changed across the migrations: {before} -> {after}")
        return 1
    print(f"    rows after migration:  {after}")
    again = tuple(q("SELECT business_name, vendor_handle, email FROM vendors LIMIT 1")[0])
    if again != snapshot:
        print(f"\n!! a row changed across the migrations: {snapshot} -> {again}")
        return 1
    print(f"    row unchanged: {again}")
    print(f"    model read: {read}")

    print(
        "\nPASS - every migration applied over live-shaped data, rows unchanged, "
        "and the columns added later are readable."
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--from", dest="from_revision", default=DEFAULT_FROM,
                        help=f"revision to seed at (default {DEFAULT_FROM})")
    parser.add_argument("--dsn", help="an existing empty database; default creates a throwaway one")
    parser.add_argument("--keep", action="store_true", help="keep the throwaway database")
    args = parser.parse_args(argv)

    if args.dsn:
        if "prod" in args.dsn.lower():
            print("Refusing: that DSN mentions production. Run this against a copy.")
            return 2
        # `--dsn` is the sync DSN: alembic and the seeding run through psycopg2.
        # The app itself connects with asyncpg, so DATABASE_URL has to be the
        # async spelling — left alone if the caller already set it.
        os.environ["DATABASE_URL_SYNC"] = args.dsn
        if not os.environ.get("DATABASE_URL"):
            async_dsn = args.dsn.replace("postgresql://", "postgresql+asyncpg://", 1)
            os.environ["DATABASE_URL"] = async_dsn
        return run(args.dsn, args.from_revision)

    try:
        import pgserver
    except ImportError:
        print("A throwaway database needs `pip install -r requirements-dev.txt` "
              "(pgserver), or pass --dsn.")
        return 2

    workdir = tempfile.mkdtemp(prefix="brief-drill-")
    server = pgserver.get_server(workdir)
    name = f"brief_drill_{uuid.uuid4().hex[:8]}"
    try:
        server.psql(f'CREATE DATABASE "{name}";')
        dsn = f"postgresql://postgres@/{name}?host={workdir}"
        os.environ["DATABASE_URL"] = f"postgresql+asyncpg://postgres@/{name}?host={workdir}"
        os.environ["DATABASE_URL_SYNC"] = dsn
        os.environ.setdefault("REDIS_URL", "redis://127.0.0.1:1/0")
        os.environ.setdefault("SECRET_KEY", "migration-drill-not-a-real-secret-000000000")
        os.environ["RUN_SCHEDULER"] = "false"
        os.environ["AUTO_CREATE_TABLES"] = "false"
        for marker in ("ENVIRONMENT", "VERCEL", "VERCEL_ENV", "RAILWAY_ENVIRONMENT"):
            os.environ.pop(marker, None)

        return run(dsn, args.from_revision)
    finally:
        if not args.keep:
            try:
                server.psql(f'DROP DATABASE IF EXISTS "{name}";')
            except Exception:  # pragma: no cover - the sandbox is discarded anyway
                pass


if __name__ == "__main__":
    sys.exit(main())
